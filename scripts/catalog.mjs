#!/usr/bin/env node
/** Validate the canonical catalog and regenerate all discovery indexes. */
import { readFileSync, writeFileSync, mkdirSync, existsSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';
import { CATEGORIES, TYPES, STATUS, validateCatalog } from '../assets/catalog.mjs';
const root = dirname(dirname(fileURLToPath(import.meta.url)));
const entries = JSON.parse(readFileSync(join(root, 'data/catalog.json'), 'utf8'));
const errors = validateCatalog(entries);
if (errors.length) { console.error(errors.join('\n')); process.exit(1); }
const check = process.argv.includes('--check');
const md = value => String(value).replace(/([\\`*_[\]<>|])/g, '\\$1').replace(/[\r\n]+/g, ' ');
const link = (label, url) => `[${md(label)}](${url.replaceAll('(', '%28').replaceAll(')', '%29')})`;
const plural = { tool: 'tools', function: 'functions', pipe: 'pipes', stack: 'stacks', integration: 'integrations' };
const anchor = name => name.toLowerCase().replace(/[^a-z0-9 -]/g, '').replaceAll(' ', '-');
const sorted = [...entries].sort((a, b) => a.name.localeCompare(b.name, 'en'));
const generated = '<!-- Generated by node scripts/catalog.mjs from data/catalog.json. Do not edit by hand. -->\n\n';
const disclaimer = '> Source documented means source or setup instructions were inspected, not runtime-tested or security-audited. Unavailable entries are historical references, not installation recommendations.\n\n';
const pages = new Map();
function detail(e) {
  return `## ${md(e.name)}\n\n${md(e.summary)}\n\n` +
    `| Field | Details |\n| --- | --- |\n` +
    [['Type', e.type], ['Use cases', e.categories.join(', ')], ['Evidence', STATUS[e.status]], ['Source checked', e.reviewed], ['Requirements', e.requirements.join('; ')], ['Compatibility', e.compatibility], ['Safety', e.risk], ['License', e.license]].map(([k,v]) => `| ${k} | ${md(v)} |`).join('\n') +
    `\n\n${link('Setup / documentation', e.guide)} \u00b7 ${link('Source', e.source)} \u00b7 ${link('Review evidence', e.evidence)}\n\n${md(e.review_note)}\n\n`;
}
for (const type of TYPES) {
  const title = plural[type][0].toUpperCase() + plural[type].slice(1);
  pages.set(`catalog/${plural[type]}.md`, generated + `# ${title}\n\n[All entries](README.md) \u00b7 [Start here](../START-HERE.md) \u00b7 [Interactive explorer](https://newnol.github.io/awesome-openwebui-stack/)\n\n` + disclaimer + sorted.filter(e => e.type === type).map(detail).join(''));
}
for (const category of CATEGORIES) {
  const title = category === 'rag' ? 'RAG' : category[0].toUpperCase() + category.slice(1).replaceAll('-', ' ');
  const items = sorted.filter(e => e.categories.includes(category));
  pages.set(`categories/${category}.md`, generated + `# ${title}\n\n[All entries](../catalog/README.md) \u00b7 [Start here](../START-HERE.md)\n\n` + disclaimer + (items.length ? items.map(e => `- ${link(e.name, `../catalog/${plural[e.type]}.md#${anchor(e.name)}`)} (${e.type}; **${STATUS[e.status]}**) - ${md(e.summary)}\n`).join('') : 'No documented entries in this category yet. [Suggest a real, installable project](../CONTRIBUTING.md).\n'));
}
pages.set('catalog/README.md', generated + '# Catalog directory\n\n[Interactive explorer](https://newnol.github.io/awesome-openwebui-stack/) \u00b7 [Start here](../START-HERE.md) \u00b7 [Contribute](../CONTRIBUTING.md)\n\n' + disclaimer + '| Entry | Type | Use cases | Evidence |\n| --- | --- | --- | --- |\n' + sorted.map(e => `| ${link(e.name, `${plural[e.type]}.md#${anchor(e.name)}`)} | ${e.type} | ${e.categories.join(', ')} | ${STATUS[e.status]} |`).join('\n') + '\n\nAll listing data comes from [`data/catalog.json`](../data/catalog.json). Review dates refer to source inspection, not compatibility testing.\n');
let stale = false;
for (const [path, content] of pages) {
  const full = join(root, path); const output = content.trimEnd() + '\n';
  if (check) {
    if (!existsSync(full) || readFileSync(full, 'utf8') !== output) { console.error(`Stale generated page: ${path}`); stale = true; }
  } else { mkdirSync(dirname(full), { recursive: true }); writeFileSync(full, output); }
}
if (stale) { console.error('Run node scripts/catalog.mjs and commit the generated pages.'); process.exit(1); }
console.log(`Validated ${entries.length} entries; ${check ? 'checked' : 'generated'} ${pages.size} Markdown pages.`);
